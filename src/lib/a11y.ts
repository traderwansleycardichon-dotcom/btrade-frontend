import type { KeyboardEvent } from 'react';

/**
 * Props that make a non-button element clickable with the mouse and
 * activatable with the keyboard (Enter or Space), like a native button.
 */
export function clickable(onActivate: () => void) {
  return {
    role: 'button' as const,
    tabIndex: 0,
    onClick: onActivate,
    onKeyDown: (e: KeyboardEvent) => {
      if (e.target !== e.currentTarget) return;
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        onActivate();
      }
    },
  };
}
