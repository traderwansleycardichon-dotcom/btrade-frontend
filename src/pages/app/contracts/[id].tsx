import React, { useRef, useState } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { ArrowLeft, Loader2, CheckCircle2, Download, AlertCircle } from 'lucide-react';
import SignatureCanvas from 'react-signature-canvas';
import toast from 'react-hot-toast';
import api from '../../../lib/api';
import { useAuth } from '../../../hooks/useAuth';

export default function ContractSignaturePage() {
  const { id } = useParams();
  const navigate = useNavigate();
  const { user, refreshUser } = useAuth();
  
  const [fullName, setFullName] = useState(user?.fullName || '');
  const [isSigning, setIsSigning] = useState(false);
  const [error, setError] = useState('');
  
  const sigPad = useRef<any>(null);

  const { data: contract, isLoading, refetch } = useQuery({
    queryKey: ['contract', id],
    queryFn: async () => {
      const res = await api.get(`/api/contracts/${id}`);
      return res.data.data;
    }
  });

  const handleClear = () => {
    sigPad.current?.clear();
  };

  const handleSign = async () => {
    if (sigPad.current?.isEmpty()) {
      toast.error('Veuillez signer le document');
      return;
    }
    if (!fullName.trim()) {
      toast.error('Veuillez entrer votre nom complet');
      return;
    }

    try {
      setIsSigning(true);
      setError('');
      
      const signatureDataUrl = sigPad.current?.getTrimmedCanvas().toDataURL('image/png');
      
      const res = await api.post(`/api/contracts/${id}/sign`, {
        signatureDataUrl,
        fullName
      });

      if (res.data.success) {
        toast.success('Contrat signé avec succès !');
        if (refreshUser) {
          await refreshUser();
        }
        refetch(); // Refresh contract data to show signed state
      }
    } catch (err: any) {
      console.error(err);
      setError(err.response?.data?.error || 'Une erreur est survenue lors de la signature');
    } finally {
      setIsSigning(false);
    }
  };

  if (isLoading) {
    return (
      <div className="flex justify-center items-center h-64">
        <Loader2 className="h-8 w-8 text-accent animate-spin" />
      </div>
    );
  }

  if (!contract) {
    return (
      <div className="text-center py-12">
        <AlertCircle className="h-12 w-12 text-red-500 mx-auto mb-4" />
        <h2 className="text-xl font-bold text-white mb-2">Contrat introuvable</h2>
        <button onClick={() => navigate('/app/contracts')} className="text-accent hover:underline">
          Retour aux contrats
        </button>
      </div>
    );
  }

  const isSigned = contract.status === 'signed';

  // Replace placeholders for display purposes (similar to what backend does)
  const parsedContent = contract.template.content
    .replace(/{{user_name}}/g, `<strong>${user?.fullName || 'Utilisateur'}</strong>`)
    .replace(/{{date}}/g, `<strong>${new Date().toLocaleDateString('fr-FR')}</strong>`);

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      {/* Header */}
      <div className="flex items-center gap-4">
        <button 
          onClick={() => navigate('/app/contracts')}
          className="p-2 bg-white/5 border border-white/10 rounded-lg hover:bg-white/10 transition-colors text-white/60"
        >
          <ArrowLeft size={16} />
        </button>
        <div>
          <h1 className="text-2xl font-bold text-white">{contract.template.title}</h1>
          <p className="text-white/60 text-sm">
            {isSigned ? 'Signé le ' + new Date(contract.signedAt).toLocaleString('fr-FR') : 'Veuillez lire et signer ci-dessous'}
          </p>
        </div>
      </div>

      {isSigned && contract.pdfUrl && (
        <div className="bg-green-500/10 border border-green-500/20 p-4 rounded-xl flex items-center justify-between">
          <div className="flex items-center gap-3">
            <CheckCircle2 className="text-green-500 h-6 w-6" />
            <span className="text-green-500 font-medium">Ce contrat a été signé électroniquement.</span>
          </div>
          <a 
            href={contract.pdfUrl}
            target="_blank"
            rel="noreferrer"
            className="flex items-center gap-2 px-4 py-2 bg-green-500 text-white rounded-lg hover:bg-green-600 transition-colors text-sm font-medium"
          >
            <Download size={16} />
            Télécharger le PDF
          </a>
        </div>
      )}

      {/* Contract Document View */}
      <div className="bg-white rounded-xl overflow-hidden shadow-2xl border border-white/10">
        <div className="p-8 md:p-12 text-black min-h-[500px]">
          {/* We use dangerouslySetInnerHTML safely here since content is generated by admin */}
          <div 
            className="prose max-w-none prose-sm"
            dangerouslySetInnerHTML={{ __html: parsedContent }}
          />

          {!isSigned && (
            <div className="mt-12 pt-8 border-t border-gray-200">
              <h3 className="text-lg font-bold mb-4">Signature Électronique</h3>
              
              <div className="grid md:grid-cols-2 gap-8">
                <div>
                  <label className="block text-sm font-medium text-gray-700 mb-2">
                    Nom complet (faisant foi)
                  </label>
                  <input
                    type="text"
                    value={fullName}
                    onChange={(e) => setFullName(e.target.value)}
                    className="w-full border border-gray-300 rounded-lg px-4 py-2 focus:border-blue-500 focus:outline-none"
                    placeholder="Prénom Nom"
                  />
                  <p className="text-xs text-gray-500 mt-2">
                    En signant ce document, vous acceptez les termes et conditions du contrat.
                  </p>
                </div>

                <div>
                  <div className="flex justify-between items-center mb-2">
                    <label className="block text-sm font-medium text-gray-700">
                      Dessinez votre signature
                    </label>
                    <button 
                      onClick={handleClear}
                      className="text-xs text-red-500 hover:underline"
                    >
                      Effacer
                    </button>
                  </div>
                  <div className="border border-gray-300 rounded-lg bg-gray-50 overflow-hidden">
                    <SignatureCanvas 
                      ref={sigPad}
                      penColor="blue"
                      canvasProps={{ className: 'w-full h-32 md:h-40 cursor-crosshair' }}
                    />
                  </div>
                </div>
              </div>

              {error && (
                <div className="mt-4 p-3 bg-red-50 text-red-500 text-sm rounded-lg border border-red-100">
                  {error}
                </div>
              )}

              <div className="mt-8 flex justify-end">
                <button
                  onClick={handleSign}
                  disabled={isSigning}
                  className="flex items-center gap-2 px-8 py-3 bg-accent text-white rounded-xl hover:bg-accent-hover transition-colors font-bold text-lg disabled:opacity-50"
                >
                  {isSigning ? <Loader2 size={20} className="animate-spin" /> : <CheckCircle2 size={20} />}
                  Signer le contrat
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
